def format_context(chunks) -> str:
    """Фрагменты для модели, сгруппированные по документам.

    Зачем группировка: шапка (даты, редакция, статус) печатается один раз над
    своими пунктами, и модель не путает пункты разных редакций и договоров.
    """
    by_doc: dict[str, list] = {}
    for c in chunks:
        by_doc.setdefault(c.doc_id, []).append(c)

    blocks = []
    for doc_chunks in by_doc.values():
        # внутри документа — в порядке текста, а не релевантности: так читается связно
        doc_chunks.sort(key=lambda c: int(c.chunk_id.rsplit("::", 1)[1]))
        first = doc_chunks[0]
        status = {"утратил силу": " — УТРАТИЛ СИЛУ", "действующая": " — действующая редакция"}.get(first.status, "")
        lines = [f"=== Документ: {first.doc_title}{status} ==="]
        header = strip_header(first.doc_header)
        if header:
            lines.append(f"Шапка: {header}")
        for c in doc_chunks:
            # Строки-инструкции для ИИ (ловушка в базе) модели не показываем совсем:
            # правило в промпте модель может и не выполнить.
            text = strip_injections(c.text).strip()
            if not text:
                continue
            label = f"[{c.clause}] " if c.clause else ""
            lead = f"(вводная часть пункта: {strip_injections(c.lead)})\n" if c.lead else ""
            lines.append(f"{label}{lead}{text}")
        blocks.append("\n".join(lines))
    return "\n\n".join(blocks)


def build_answer_messages(question: str, chunks, history: list[dict]) -> list[dict]:
    parts = [f"Сегодня: {datetime.date.today():%d.%m.%Y}."]
    if history:
        parts.append("Предыдущий диалог:\n" + history_as_text(history))
    parts.append("Фрагменты документов из базы знаний:\n" + format_context(chunks))
    # Вопрос в тегах: модель видит границу между данными и инструкциями (защита от инъекций).
    parts.append(f"Вопрос сотрудника:\n<вопрос>\n{question}\n</вопрос>")
    parts.append("Ответь на вопрос по правилам. Используй только фрагменты выше.")
    return [{"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": "\n\n".join(parts)}]


