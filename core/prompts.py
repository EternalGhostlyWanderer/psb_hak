EXAMPLES_HEADER = ("ПРИМЕРЫ ВОПРОСОВ И ОТВЕТОВ (образец полноты и стиля; факты для ответа бери "
                   "только из фрагментов текущего вопроса, не из примеров):")


def system_prompt(question: str = "") -> str:
    """Правила + образцы ответов. При LA_FEWSHOT_LOO=1 образец с тем же вопросом
    пропускается: так локальная проверка на демо-вопросах остаётся честной."""
    blocks = []
    for raw, answer in EXAMPLES:
        last, history = parse_question(raw)
        if config.FEWSHOT_LOO and question and last.strip() == question.strip():
            continue
        shown = raw if history else last
        blocks.append(f"Вопрос: {shown}\nОтвет: {answer}")
    return RULES + "\n\n" + EXAMPLES_HEADER + "\n" + "\n\n".join(blocks)


